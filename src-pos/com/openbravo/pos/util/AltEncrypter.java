package com.openbravo.pos.util;

import java.io.UnsupportedEncodingException;
import java.security.*;
import java.util.logging.Level;
import java.util.logging.Logger;
import javax.crypto.*;

/**
 * Configuration encrypter kept under its historical name for compatibility.
 *
 * <p>New values are written with {@link SecureEncrypter} (AES-128-GCM, random
 * nonce, key derived from a local secret). The old 3DES/ECB cipher is retained
 * <em>only</em> to decrypt values already stored in existing installations;
 * nothing new is ever encrypted with it.</p>
 *
 * @author JG uniCenta
 */
public class AltEncrypter {

    private static final Logger logger = Logger.getLogger("com.openbravo.pos.util.AltEncrypter");

    private final String m_passPhrase;
    private Cipher cipherDecrypt;

    /** Creates a new instance of Encrypter
     * @param passPhrase */
    public AltEncrypter(String passPhrase) {
        m_passPhrase = passPhrase;
        try {
            // Only needed for legacy ciphertexts generated by uniCenta <= 3.81.
            SecureRandom sr = SecureRandom.getInstance("SHA1PRNG");
            sr.setSeed(passPhrase.getBytes("UTF8"));
            KeyGenerator kGen = KeyGenerator.getInstance("DESEDE");
            kGen.init(168, sr);
            Key key = kGen.generateKey();

            cipherDecrypt = Cipher.getInstance("DESEDE/ECB/PKCS5Padding");
            cipherDecrypt.init(Cipher.DECRYPT_MODE, key);
        } catch (UnsupportedEncodingException | NoSuchPaddingException
                | NoSuchAlgorithmException | InvalidKeyException e) {
            logger.log(Level.WARNING,
                    "3DES not available: legacy encrypted configuration values cannot be read", e);
        }
    }

    /**
     * Encrypts with AES-GCM.
     *
     * @param str clear text
     * @return versioned ciphertext, or null on failure
     */
    public String encrypt(String str) {
        return SecureEncrypter.encrypt(m_passPhrase, str);
    }

    /**
     * Decrypts both the new AES-GCM format and the legacy 3DES/ECB format.
     *
     * @param str stored ciphertext (without the outer {@code crypt:} prefix)
     * @return clear text, or null when it cannot be decrypted
     */
    public String decrypt(String str) {
        if (str == null) {
            return null;
        }
        // Some callers strip the outer "crypt:" prefix themselves, others
        // pass the stored value straight through: accept both.
        String value = str.startsWith("crypt:") ? str.substring(6) : str;
        if (value.startsWith(SecureEncrypter.PREFIX + "$")) {
            return SecureEncrypter.decrypt(m_passPhrase, value);
        }
        return legacyDecrypt(value);
    }

    private String legacyDecrypt(String str) {
        if (cipherDecrypt == null) {
            logger.warning("Cannot decrypt legacy value: 3DES is not available");
            return null;
        }
        try {
            return new String(cipherDecrypt.doFinal(StringUtils.hex2byte(str)), "UTF8");
        } catch (UnsupportedEncodingException | BadPaddingException | IllegalBlockSizeException
                | IllegalArgumentException e) {
            logger.log(Level.WARNING, "Cannot decrypt legacy configuration value", e);
            return null;
        }
    }
}
